"""Redact explicitly supplied secrets before returning external-tool output."""

from __future__ import annotations

import json
import re
from typing import Any, Mapping
from urllib.parse import quote, quote_plus

_SECRET_NAME = re.compile(r"(?:TOKEN|SECRET|PASSWORD|PASSWD|CREDENTIAL|API_KEY|ACCESS_KEY|PRIVATE_KEY)", re.I)


def redact_text(text: str, environment: Mapping[str, str] | None) -> str:
    """Remove known secret values and common JSON/URL encodings.

    This cannot infer credentials generated by a third-party program or arbitrary
    transformations of secrets. Caller-supplied credentials stay in environment
    variables and must not be deliberately printed by trusted tools.
    """
    if not environment:
        return text
    replacements: set[str] = set()
    for key, value in environment.items():
        if isinstance(key, str) and isinstance(value, str) and value and _SECRET_NAME.search(key):
            replacements.update((value, json.dumps(value, ensure_ascii=True)[1:-1],
                                 json.dumps(value, ensure_ascii=False)[1:-1], quote(value, safe=""), quote_plus(value)))
    for secret in sorted(replacements, key=len, reverse=True):
        text = text.replace(secret, "[REDACTED]")
    return text


def redact_data(value: Any, environment: Mapping[str, str] | None) -> Any:
    """Return a JSON-shaped copy with known secrets removed from strings and keys."""
    if isinstance(value, str):
        return redact_text(value, environment)
    if isinstance(value, list):
        return [redact_data(item, environment) for item in value]
    if isinstance(value, dict):
        return {redact_text(key, environment): redact_data(item, environment) for key, item in value.items()}
    return value
